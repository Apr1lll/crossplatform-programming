from turtle import *
t = Turtle()
t.screen.setup(800, 800)
t.hideturtle()
t.pensize(10)
t.color("darkgreen")
t.up()
t.goto(100, 200)
t.down()
t.goto(-100, 200)
t.goto(-100, -100)
t.goto(100, -100)
t.goto(100, 50)
t.goto(-100, 50)
t.up()
t.color("black")
t.goto(0, -200)
t.write("Зародов Михаил Александрович", align="center", font=("Arial", 20, "bold"))
t.screen.exitonclick()
t.screen.mainloop()
