common={}
for i in dict1:
  if i in common_words:
    common[i] = dict1[i]+dict2[i]

pairs=[]
for i in common:
  pairs.append((common[i], i))

pairs.sort(reverse=True)

sorted_common = {}
for freq, word in pairs:
  sorted_common[word] = freq
print(f"Отсортированные: {sorted_common}")

for i in list(sorted_common.keys()):
  if len(i) < 3:
    del sorted_common[i]
