def make_dict(text):
  split_text = text.split()
  trash_simbols = "-—,?.:;"


  lower_words=[]
  for i in split_text:
    if i not in trash_simbols:
      lower_words.append(i.lower())

  count={}

  for word in lower_words:
    count[word] = count.get(word, 0) + 1
  return count


