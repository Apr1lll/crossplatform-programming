s = "У лукоморья 123 дуб зеленый"

# a. Встречается ли буква 'я' и её позиция
if 'я' in s:
    print("a) Буква 'я' найдена на позиции:", s.index('я'))
else:
    print("a) Буква 'я' не найдена")

# b. Сколько раз встречается буква 'у'
print("b) Буква 'у' встречается", s.lower().count('у'), "раз")

# c. Состоит ли строка только из букв
if s.replace(" ", "").isalpha():
    print("c) Строка состоит только из букв")
else:
    print("c) Строка содержит не только буквы. В верхнем регистре:", s.upper())

# d. Длина строки
print("d) Длина строки:", len(s))
if len(s) > 4:
    print("   Строка в нижнем регистре:", s.lower())

# e. Заменить первый символ на 'О'
s2 = 'О' + s[1:]
print("e) Строка после замены первого символа:", s2)

# f. Итоговый вывод
print("\nf) Итоговый результат:", s2)