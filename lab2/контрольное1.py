# a. Записываем строку с клавиатуры
s = input("Введите строку: ")

# b. Третий символ строки (индекс 2)
print("b) Третий символ:", s[2])

# c. Предпоследний символ строки (индекс -2)
print("c) Предпоследний символ:", s[-2])

# d. Первые пять символов строки
print("d) Первые пять символов:", s[:5])

# e. Вся строка, кроме последних двух символов
print("e) Вся строка кроме последних двух символов:", s[:-2])

# f. Все символы с чётными индексами (0, 2, 4, ...)
print("f) Символы с чётными индексами:", s[::2])

# g. Все символы с нечётными индексами (1, 3, 5, ...)
print("g) Символы с нечётными индексами:", s[1::2])

# h. Все символы в обратном порядке
print("h) Символы в обратном порядке:", s[::-1])

# i. Все символы через один в обратном порядке, начиная с последнего
print("i) Через один в обратном порядке:", s[::-2])

# j. Длина строки
print("j) Длина строки:", len(s))